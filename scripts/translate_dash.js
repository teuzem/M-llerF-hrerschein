['fr', 'en'].forEach(lang => {
  const fileData = JSON.parse(fs.readFileSync(localesPath[lang], 'utf8'));
  const target = map[lang];
  for (const [key, val] of Object.entries(target)) {
    fileData[key] = val;
  }
  fs.writeFileSync(localesPath[lang], JSON.stringify(fileData, null, 2), 'utf8');
});

